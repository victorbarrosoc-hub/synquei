export const tipoDe = (id) => TIPOS.find((t) => t.id === id) || null

/** Aplica o ponto de partida do tipo ao projeto (sincronia + multicâmera). */
export function aplicarTipo(p, id, multicam) {
  const t = tipoDe(id) || tipoDe('outro')
  p.type = t.id
  Object.assign(p.sync, t.sync)
  p.export.multicam = multicam == null ? t.multicam : !!multicam
  p.export.fcp = p.export.multicam ? (p.export.fcp === 'multicam' ? 'multicam' : 'both') : 'timeline'
  p.updatedAt = Date.now()
  return p
}
